import assert from "node:assert/strict"
import { randomUUID } from "node:crypto"
import type { FastifyInstance } from "fastify"
import type { Pool } from "pg"

export async function verifyWarrantyCases(app: FastifyInstance, db: Pool, tenant: string, role: string, memberRole: string, order: string, product: string) {
  const headers = { authorization: "Bearer reader", "x-tenant-id": tenant }
  const url = "/api/v1/warranty-cases"
  const denied = await app.inject({ url, headers })
  assert.equal(denied.statusCode, 403, denied.body)
  await db.query("INSERT INTO role_permissions(role_id,permission_code) VALUES ($1,'service.warranties.read'),($1,'service.warranties.manage'),($1,'service.warranties.approve')", [memberRole])
  await db.query(`GRANT UPDATE(id) ON tenants TO ${role}; GRANT INSERT,UPDATE ON warranty_cases TO ${role}; GRANT INSERT ON warranty_case_events,domain_commands,audit_log,outbox_events TO ${role}`)
  const payload = { title: "Falha no equipamento", description: "Ruído durante a utilização do equipamento.", criticality: "high", orderId: order, productId: product, serialNumber: "S-ÚNICA" }
  const command = { method: "POST" as const, url, headers: { ...headers, "idempotency-key": randomUUID() }, payload }
  const opened = await app.inject(command)
  assert.equal(opened.statusCode, 201, opened.body)
  const saved = opened.json().data
  assert.equal(saved.customerId, tenant)
  assert.equal(saved.orderId, order)
  const replayed = await app.inject(command)
  assert.equal(replayed.json().data.id, saved.id)
  assert.equal(replayed.headers["idempotency-replayed"],"true")
  const historicalKey=randomUUID()
  const oldInput={...payload,policyId:null,customerId:null,lot:null}
  await db.query("INSERT INTO domain_commands(tenant_id,auth_subject,command_key,scope,request,result) VALUES($1,'reader',$2,'warranty.case.create',$3,$4)",[tenant,historicalKey,oldInput,{tenantId:tenant,data:saved}])
  const previousRelease={...command,headers:{...headers,"idempotency-key":historicalKey},payload:{...payload,documentId:null,lineNumber:null}}
  const recovered=await app.inject(previousRelease)
  assert.equal(recovered.statusCode,200,recovered.body)
  assert.equal(recovered.headers["idempotency-replayed"],"true")
  assert.equal(recovered.json().data.id,saved.id)
  assert.equal((await app.inject({...previousRelease,payload:{...payload,title:"Outro protocolo"}})).statusCode,409)
  const invalidProduct = await app.inject({ ...command, headers: { ...headers, "idempotency-key": randomUUID() }, payload: { ...payload, productId: randomUUID() } })
  assert.equal(invalidProduct.statusCode, 422, invalidProduct.body)
  const cases = await app.inject({ url: url + "?q=" + encodeURIComponent("S-ÚNICA") + "&status=opened&limit=1", headers })
  assert.equal(cases.statusCode, 200, cases.body)
  assert.equal(cases.json().total, 1)
  assert.equal(cases.json().data[0].productName, "Banco")
  const pageAfter = await app.inject({ url: url + "?offset=1&limit=1", headers })
  assert.equal(pageAfter.json().total, 1)
  assert.deepEqual(pageAfter.json().data, [])
  const detail = await app.inject({ url: url + "/" + saved.id, headers })
  assert.equal(detail.statusCode, 200, detail.body)
  assert.equal(detail.headers.etag, '"1"')
  assert.deepEqual(detail.json().data.timeline.map((event: {eventType: string}) => event.eventType), ["opened"])
  const move = (action:string, revision:number, payload: Record<string, unknown>) => app.inject({
    method: "POST", url: url + "/" + saved.id + "/" + action,
    headers: { ...headers, "if-match": '"' + revision + '"', "idempotency-key": randomUUID() }, payload,
  })
  assert.equal((await move("transition", 1, { status: "closed", details: {} })).statusCode, 409)
  const assigned = await move("assignment", 1, { assignedTo:null,queue:"Bancada",slaDueAt:null })
  assert.equal(assigned.statusCode, 200, assigned.body)
  assert.equal((await move("transition", 1, { status:"triage",details:{} })).statusCode, 412)
  const triage = await move("transition", 2, { status:"triage",details:{} })
  assert.equal(triage.headers.etag, '"3"', triage.body)
  await db.query(`GRANT INSERT ON warranty_approvals,warranty_service_orders TO ${role}`)
  const labor = await move("service-order", 3, { diagnosis:"Reparar componente", report:{}, scheduledAt:null, laborCents:10000 })
  assert.equal(labor.statusCode, 200, labor.body)
  assert.equal((await move("approval", 4, { action:"refund",decision:"approved",notes:"",amountCents:0 })).statusCode, 422)
  const approved = await move("approval", 4, { action:"refund",decision:"approved",notes:"",amountCents:50005 })
  assert.equal(approved.statusCode, 200, approved.body)
  const updated = (await app.inject({ url:url + "/" + saved.id,headers })).json().data
  assert.equal(updated.serviceOrders[0].laborCents, 10000)
  assert.equal(updated.approvals[0].amountCents, 50005)
  await db.query(`GRANT INSERT,UPDATE ON stock_balances,warranty_service_orders,warranty_quarantines TO ${role}; GRANT INSERT ON warranty_service_order_parts,stock_movements TO ${role}`)
  await db.query(`GRANT UPDATE(stock_changed) ON inventory_count_lines TO ${role}; GRANT INSERT ON stock_cost_inputs TO ${role}; GRANT INSERT,UPDATE ON stock_cost_jobs,stock_cost_dispatch TO ${role}`)
  await db.query("INSERT INTO stock_balances(tenant_id,product_id,quantity_micros) VALUES($1,$2,2500000)",[tenant,product])
  const part = { method:"POST" as const,url:"/api/v1/warranty-service-orders/"+updated.serviceOrders[0].id+"/parts",
    headers:{...headers,"if-match":'"1"',"idempotency-key":randomUUID()},payload:{productId:product,quantity:"1.500000",amountCents:1200} }
  const registered = await app.inject(part)
  assert.equal(registered.statusCode,200,registered.body)
  assert.equal((await app.inject(part)).json().data.stockMovementId, registered.json().data.stockMovementId)
  const balance = async () => (await db.query("SELECT quantity_micros::text AS units FROM stock_balances WHERE tenant_id=$1 AND product_id=$2",[tenant,product])).rows[0].units
  assert.equal(await balance(),"1000000")
  const document=randomUUID()
  await db.query(`GRANT INSERT ON warranty_policies,warranty_sold_equipment TO ${role}`)
  await db.query("INSERT INTO fiscal_nfe_drafts(tenant_id,id,environment,model,profile_revision,company_revision,issuer_snapshot,details,products_total_cents) VALUES($1,$2,'production',55,1,1,'{}',$3,10000)",[tenant,document,{sourceOrderId:order,items:[{code:"LD-1",quantity:"1.0000"}]}])
  await db.query("INSERT INTO fiscal_nfe_documents(tenant_id,id,environment,source_order_id,model,status,series,number,issued_at,random_code,access_key,signed_xml,authorized_xml,protocol) VALUES($1,$2,'production',$3,55,'authorized',1,27,(now()-interval '5 days')::text,'00000001',repeat('1',44),'<fixture/>','<fixture/>','135000000000000')",[tenant,document,order])
  const createRecord=(resource:string,body:Record<string,unknown>)=>app.inject({method:"POST",url:"/api/v1/warranty-"+resource,headers:{...headers,"idempotency-key":randomUUID()},payload:body})
  const policy=await createRecord("policies",{name:"Equipamento • um ano",durationDays:365,coverageType:"contractual",scope:{productId:product}})
  assert.equal(policy.statusCode,201,policy.body)
  const equipment={serialNumber:"E-428",lineNumber:1,documentId:document,policyId:policy.json().data.id}
  const link=await createRecord("equipment",equipment)
  assert.equal(link.statusCode,201,link.body)
  assert.equal((await createRecord("equipment",{...equipment,serialNumber:"E-429"})).statusCode,409)
  const serial=await app.inject({url:"/api/v1/warranty-equipment?serialNumber=e-428",headers})
  assert.equal(serial.json().data.orderId,order,serial.body)
  assert.equal(serial.json().data.remainingDays,360)
  const traced=await createRecord("cases",{title:"Cobertura pela série",description:"Equipamento aguarda análise técnica.",criticality:"normal",serialNumber:"e-428"})
  assert.equal(traced.statusCode,201,traced.body)
  assert.equal(traced.json().data.customerId,tenant)
  assert.equal(traced.json().data.coverageStatus,"eligible")
  const insufficient = await app.inject({...part,headers:{...part.headers,"if-match":'"2"',"idempotency-key":randomUUID()}})
  assert.equal(insufficient.statusCode,409,insufficient.body)
  const quarantined=await move("quarantine",5,{productId:product,quantity:"1",reason:"Conferência da peça"})
  assert.equal(quarantined.statusCode,200,quarantined.body)
  assert.equal(await balance(),"0")
  const release=await app.inject({method:"POST",url:"/api/v1/warranty-quarantines/"+quarantined.json().data.id+"/transition",
    headers:{...part.headers,"idempotency-key":randomUUID()},payload:{status:"released",details:{}}})
  assert.equal(release.statusCode,200,release.body)
  assert.equal(await balance(),"1000000")

  await db.query(`GRANT INSERT ON warranty_case_records TO ${role}`)
  const latest=await app.inject({url:url+"/"+saved.id,headers})
  const revision=Number(latest.json().data.revision)
  const pdf=Buffer.from("%PDF-1.4\nRegistro local de assistência\n%%EOF")
  const receipt={method:"POST" as const,url:url+"/"+saved.id+"/records",headers:{...headers,"if-match":`"${revision}"`,"idempotency-key":randomUUID()},
    payload:{kind:"evidence",title:"Foto e laudo recebidos",filename:"registro de fábrica.pdf",mediaType:"application/pdf",base64:pdf.toString("base64")}}
  const attached=await app.inject(receipt)
  assert.equal(attached.statusCode,200,attached.body)
  assert.equal((await app.inject(receipt)).headers["idempotency-replayed"],"true")
  const download=await app.inject({url:"/api/v1/warranty-evidence/"+attached.json().data.id+"/file",headers})
  assert.equal(download.statusCode,200,download.body)
  assert.deepEqual(download.rawPayload,pdf)
  assert.match(download.headers["content-disposition"] as string,/attachment/)
  assert.equal((await db.query("SELECT request::text FROM domain_commands WHERE command_key=$1",[receipt.headers["idempotency-key"]])).rows[0].request.includes(pdf.toString("base64")),false)
  assert.equal((await move("records",revision+1,{...receipt.payload,base64:Buffer.from("mídia inválida").toString("base64")})).statusCode,422)
  const report=await move("records",revision+1,{kind:"report",title:"Resultado da inspeção",serviceOrderId:labor.json().data.id,cause:"Desgaste",diagnosis:"Rolamento gasto",conclusion:"Peça trocada e equipamento verificado",scheduledAt:null,status:"completed"})
  assert.equal(report.statusCode,200,report.body)
  assert.equal((await db.query("SELECT status FROM warranty_service_orders WHERE id=$1",[labor.json().data.id])).rows[0].status,"completed")
  const contract=randomUUID()
  await db.query(`INSERT INTO commercial_contracts(id,tenant_id,customer_id,order_id,template_id,template_name,template_snapshot,snapshot,recipients,fields,fingerprint,status)
    VALUES($1,$2,$2,$3,1,'Termo de assistência','{}','{}','[]','[]',$4,'sent')`,[contract,tenant,order,randomUUID()])
  const term={kind:"term",title:"Termo de assistência",contractId:contract}
  assert.equal((await move("records",revision+2,term)).statusCode,403)
  await db.query("INSERT INTO role_permissions(role_id,permission_code) VALUES($1,'sales.orders.read') ON CONFLICT DO NOTHING",[memberRole])
  const linked=await move("records",revision+2,term)
  assert.equal(linked.statusCode,200,linked.body)
  const records=()=>app.inject({url:url+"/"+saved.id+"/records",headers})
  assert.equal((await records()).json().contracts[0].accepted,false)
  await db.query("UPDATE commercial_contracts SET status='completed' WHERE id=$1",[contract])
  assert.equal((await records()).json().contracts[0].accepted,false)
  await db.query("INSERT INTO commercial_contract_files(id,tenant_id,contract_id,kind,position,sha256,content) VALUES($1,$2,$3,'signed',0,repeat('a',64),$4)",[randomUUID(),tenant,contract,pdf])
  assert.equal((await records()).json().contracts[0].accepted,true)
  const measured=await app.inject({url:"/api/v1/warranty-metrics",headers})
  assert.equal(measured.statusCode,200,measured.body)
  assert.ok(measured.json().causes.some((v:{cause:string;n:number})=>v.cause==="Desgaste" && v.n===1))
  assert.equal(measured.json().data.reduce((sum:bigint,r:{costCents:string})=>sum+BigInt(r.costCents),0n).toString(),measured.json().costCents)
  assert.equal(measured.json().recoveryCents,"0")
  await db.query(`INSERT INTO warranty_cases(tenant_id,id,protocol,title,description,criticality)
    SELECT $1,gen_random_uuid(),'GAR-ACERVO-'||n,'Inspeção de acervo','Protocolo sintético do histórico','normal' FROM generate_series(1,215) n`,[tenant])
  const archive=await app.inject({url:url+"?q=ACERVO&offset=200&limit=25",headers})
  assert.equal(archive.statusCode,200,archive.body)
  assert.equal(archive.json().total,215)
  assert.equal(archive.json().counts.opened,215)
  assert.equal(archive.json().data.length,15)
}

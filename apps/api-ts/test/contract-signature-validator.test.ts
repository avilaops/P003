import { readFileSync } from "node:fs";
import test from "node:test";
import { verifyBundle } from "../src/modules/contract-signatures/validator-bundle.js";
import { approvedTrust, ICP_ROOT_HASHES, REGISTRY_SHA256 } from "../src/modules/contract-signatures/validator-config.js";
import { BUNDLE_TYPE, canonical, ContractSignatureValidationError, encodeRequest, POLICY_SHA256, REPORT_TYPE, sha256,
  type ValidatorSigner, type WireInput } from "../src/modules/contract-signatures/validator-wire.js";

const root = new URL("../../../", import.meta.url);
const roots = readFileSync(new URL("deploy/fiscal/icp-brasil-roots.pem", root));
const trust = approvedTrust(roots, Buffer.alloc(0));

function vector(operation: "preflight" | "increment") {
  // Constructed protocol vectors generated by the actual Python encoder.
  const raw = JSON.parse(readFileSync(new URL("apps/api-ts/test/fixtures/contract-wire/" + operation + ".json", root), "utf8"));
  const part = (name: string) => Buffer.from(raw.parts[name], "base64");
  const context = { tenantId: raw.tenantId, envelopeId: raw.envelopeId, documentId: raw.documentId };
  const input: WireInput = operation === "preflight" ? { operation, base: part("base") }
    : { operation, base: part("base"), parent: part("parent"), candidate: part("candidate"),
        signer: raw.signer, previousSigners: raw.previousSigners };
  const key = { keyId: raw.keyId, secret: Buffer.from(raw.keyBase64, "base64") };
  const request = encodeRequest(context, input, trust.sha256, key, raw.requestId, raw.sentAt);
  const body = Buffer.from(raw.responseBundleBase64, "base64");
  const verify = (bytes = body, headers = raw.responseHeaders, time = raw.sentAt * 1000) =>
    verifyBundle(bytes, headers, request, key, trust, time);
  return { raw, context, input, key, request, body, verify };
}

test("reviewed ICP root registry and both request frames match the Python protocol byte-for-byte", () => {
  const registry = readFileSync(new URL("apps/contract-signature-validator/src/contract_signature_validator/trust_registry.json", root));
  assert.equal(sha256(registry), REGISTRY_SHA256);
  assert.deepEqual(JSON.parse(registry.toString()).roots.map((r: { sha256: string }) => r.sha256), ICP_ROOT_HASHES);
  assert.throws(() => approvedTrust(readFileSync(new URL("apps/api-ts/test/fixtures/contract-wire/tls-test-ca.pem", root)), Buffer.alloc(0)));
  for (const op of ["preflight", "increment"] as const) {
    const { raw, request } = vector(op);
    assert.equal(POLICY_SHA256, raw.policySha256);
    assert.equal(trust.sha256, raw.trustBundleSha256);
    // Compare booleans to keep any failure output free of identities and HMACs.
    assert.ok(request.frame.equals(Buffer.from(raw.frameBase64, "base64")));
    assert.ok(canonical(request.headers) === canonical(raw.headers));
  }
});

test("preflight authenticates both layers and correlates the bundle, clock, trust and inventory", () => {
  const fixture = vector("preflight");
  const receipt = fixture.verify();
  assert.equal(receipt.verdict, "accepted");
  assert.equal(receipt.bundleSha256, fixture.raw.responseBundleSha256);
  assert.equal(receipt.evidenceSetSha256, fixture.raw.evidenceSetSha256);
  assert.equal(receipt.requestSha256, fixture.raw.frameSha256);
  const corrupt = Buffer.from(fixture.body);
  corrupt[corrupt.length - 1] = corrupt[corrupt.length - 1]! ^ 1;
  assert.throws(() => fixture.verify(corrupt));
  assert.throws(() => fixture.verify(undefined, { ...fixture.raw.responseHeaders, "transfer-encoding": "chunked" }));
  assert.throws(() => fixture.verify(undefined, undefined, (fixture.raw.sentAt + 61) * 1000));
});

type Part = { name: string; index: number; length: number; sha256: string };
type Check = { name: string; verdict: string; reason: string; evidenceHashes: string[] };

// Constructed offline evidence only. Re-sealing mutations exercises independent checks
// after transport authentication succeeds. No personal signing credentials are used.
function incrementFixture() {
  const f = vector("increment");
  const magic = Buffer.from("AVILA-CVB1\n");
  const start = magic.length + 4;
  let offset = start + f.body.readUInt32BE(magic.length);
  const meta = JSON.parse(f.body.subarray(start, offset).toString());
  const parts: Buffer[] = meta.parts.map((p: Part) => {
    const b = f.body.subarray(offset, offset + p.length);
    offset += p.length;
    return b;
  });
  const wrapper = JSON.parse(parts[0]!.toString());
  const checks: Check[] = wrapper.report.checks;
  const certificate = Buffer.from("wire test certificate bytes");
  const crl = Buffer.from("wire test revocation bytes");
  const chain = checks.find(c => c.name === "chain")!;
  const revocation = checks.find(c => c.name === "revocation")!;
  chain.reason = revocation.reason = "chain_and_revocation_validated";
  chain.evidenceHashes = [sha256(certificate)];
  revocation.evidenceHashes = [sha256(crl)];
  meta.evidenceSetSha256 = sha256(canonical({ observedAt: wrapper.checkedAt, certificates: chain.evidenceHashes,
    crls: revocation.evidenceHashes, ocsps: [] }));
  checks.find(c => c.name === "evidence_set")!.evidenceHashes = [meta.evidenceSetSha256];
  meta.parts.push({ name: "certificates", index: 0 }, { name: "crls", index: 0 });
  parts.push(certificate, crl);
  function signed(body: Buffer, type: string) {
    const digest = sha256(body);
    const message = ["AVILA-CV-RESPONSE/1", f.key.keyId, f.raw.requestId, f.raw.frameSha256, digest, body.length, ""].join("\n");
    return { "content-type": type, "content-length": String(body.length), "x-validation-response-sha256": digest,
      "x-validation-response-mac": "HMAC-SHA256 " + f.key.keyId + ":" + createHmac("sha256", f.key.secret).update(message).digest("hex") };
  }
  function verify(corruptInnerMac = false) {
    wrapper.reportSha256 = sha256(canonical(wrapper.report));
    parts[0] = Buffer.from(canonical(wrapper));
    meta.responseHeaders = signed(parts[0], REPORT_TYPE);
    if (corruptInnerMac) meta.responseHeaders["x-validation-response-mac"] = "";
    parts.forEach((p, i) => Object.assign(meta.parts[i], { length: p.length, sha256: sha256(p) }));
    const header = Buffer.from(canonical(meta));
    const length = Buffer.alloc(4);
    length.writeUInt32BE(header.length);
    const bundle = Buffer.concat([magic, length, header, ...parts]);
    return f.verify(bundle, signed(bundle, BUNDLE_TYPE));
  }
  return { wrapper, checks, chain, revocation, meta, parts, verify };
}

test("increment requires the ordered identities, PDF hashes, chain and revocation material", () => {
  assert.throws(() => vector("increment").verify()); // Empty constructed Python transport vector.
  assert.equal(incrementFixture().verify().verdict, "accepted");
  const mutations: ((f: ReturnType<typeof incrementFixture>) => void)[] = [
    f => { f.wrapper.report.checks = f.checks.filter(c => c.name !== "identity"); },
    f => { f.checks.push(f.checks[0]!); },
    f => { f.wrapper.report.binding.participantId = f.wrapper.tenantId; },
    f => { f.wrapper.report.binding.parentSha256 = f.wrapper.report.binding.candidateSha256; },
    f => { f.wrapper.report.binding.candidateSha256 = f.wrapper.report.binding.parentSha256; },
    f => { f.wrapper.requestSha256 = "0".repeat(64); },
    f => { f.wrapper.report.trustProfile = "synthetic_not_icp"; },
    f => { f.wrapper.report.timestampStatus = "unsupported"; },
    f => { f.wrapper.report.binding.trustBundleSha256 = "0".repeat(64); },
    f => { f.parts[1] = f.parts[3]!; },
    f => { f.meta.evidenceSetSha256 = "0".repeat(64); },
    f => { f.revocation.evidenceHashes = f.chain.evidenceHashes; },
    f => { f.revocation.evidenceHashes = []; },
    f => { f.meta.parts[4].name = "certificates"; },
    f => { f.checks.find(c => c.name === "identity")!.verdict = "invalid"; },
  ];
  for (const mutate of mutations) {
    const f = incrementFixture();
    mutate(f);
    assert.throws(() => f.verify());
  }
  assert.throws(() => incrementFixture().verify(true));
  for (const state of ["invalid", "unsupported", "indeterminate"]) {
    const f = incrementFixture();
    f.chain.verdict = f.wrapper.report.verdict = state;
    assert.throws(() => f.verify(), (e: unknown) => e instanceof ContractSignatureValidationError && e.statusCode === 422);
  }
});

test("ordered increments reject a changed parent, duplicate CPF, duplicate participant and missing predecessor", () => {
  const f = vector("increment");
  assert.ok(f.input.operation === "increment");
  const i = f.input;
  const encode = (previousSigners: readonly ValidatorSigner[], parent: Buffer) => encodeRequest(f.context,
    { ...i, previousSigners, parent }, trust.sha256, f.key, f.raw.requestId, f.raw.sentAt);
  const previous = i.previousSigners[0]!;
  for (const invalid of [[previous, previous], [{ ...previous, expectedCpf: i.signer.expectedCpf }],
    [{ ...previous, participantId: i.signer.participantId }], [{ ...previous, expectedCpf: "00000000000" }], []]) {
    assert.throws(() => encode(invalid, i.parent), { statusCode: 422 });
  }
  assert.throws(() => encode([previous], Buffer.from("different revision")), { statusCode: 422 });
  const third = { participantId: "80000000-0000-4000-8000-000000000001", expectedCpf: "12345678909" };
  const people = [previous, third];
  const ordered = encode(people, i.parent);
  assert.ok(canonical(ordered.metadata.previousSigners) === canonical(people));
  assert.notEqual(ordered.digest, encode([...people].reverse(), i.parent).digest);
  const substituted = { ...third, expectedCpf: "39053344705" };
  assert.notEqual(ordered.digest, encode([previous, substituted], i.parent).digest);
});

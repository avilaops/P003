import assert from "node:assert/strict"
import { randomUUID } from "node:crypto"
import test from "node:test"
import { commercialFixture } from "./commercial-fixture.js"
import { localCommercePostgres } from "./local-commerce-postgres.js"

test("Gestão corrige custo e política, republica e recupera a simulação com a alçada do vendedor", {skip:!process.env.API_TS_TEST_ADMIN_URL}, async () => {
  await localCommercePostgres(async ({seed,app,tenant,other,clerk}) => {
    const { parameters,rules,input,sources } = commercialFixture()
    const product = sources[0]!.productId, category = randomUUID()
    const cost = {productLine:"imported",purchaseCostCents:530606,taxCreditBps:2780,packagingCents:0}
    const settings = "/commercial-settings/imported", costs = "/product-costs/" + product
    const prices = "/price-tables/imported", display = "/commercial/tables/imported?destinationState=SP&taxpayer=false"
    const policy = "/commercial/approval-settings"
    const request = (method:"GET"|"POST"|"PUT", path:string, payload?:object, revision?:number, key?:string, company=tenant) =>
      app.inject({method,url:"/api/v1"+path,headers:{authorization:"Bearer cashier","x-tenant-id":company,
        ...(revision === undefined ? {} : {"if-match":'"'+revision+'"'}), ...(key ? {"idempotency-key":key} : {})},...(payload ? {payload} : {})})
    const checked = (r:{statusCode:number;body:string;json():any},status=200) => { assert.equal(r.statusCode,status,r.body);return r.json() }
    const grant = (rights:string[]) => seed.query("INSERT INTO role_permissions(role_id,permission_code) SELECT $1,unnest($2::text[]) ON CONFLICT DO NOTHING",[clerk,rights])
    await seed.query("INSERT INTO products(id,tenant_id,sku,name,unit,price_cents,status) VALUES($1,$2,'LD-A001','Equipamento','UN',123,'active')",[product,tenant])
    await seed.query("INSERT INTO financial_categories(id,tenant_id,code,name,status,revision,direction) VALUES($1,$2,'ALUG','Aluguel','active',1,'expense')",[category,tenant])
    await grant(["sales.orders.read","sales.approvals.manage"])
    checked(await request("GET",settings),403)
    checked(await request("PUT",policy,rules,1),403)
    checked(await request("GET",costs),403)
    checked(await request("GET",prices+"/preview"),403)
    checked(await request("GET","/financial-categories?limit=100"),403)
    assert.equal(checked(await request("GET",display)).canManage,false)
    await grant(["platform.company.manage","finance.categories.read"])
    checked(await request("GET",prices,undefined,undefined,undefined,other),403)
    const categories=checked(await request("GET","/financial-categories?q=alu&limit=100"))
    assert.equal(categories.canEdit,false)
    assert.equal(categories.data[0].id,category)
    const expense = {description:" Aluguel mensal ",categoryId:category,amountCents:40000,startsOn:"2020-01-01",endsOn:null,status:"active"}
    checked(await request("POST","/fixed-expenses",{...expense,startsOn:"1800-01-01"},undefined,randomUUID()),422)
    const expenseKey = randomUUID()
    const expenseId = checked(await request("POST","/fixed-expenses",expense,undefined,expenseKey),201).data.id
    assert.equal(checked(await request("POST","/fixed-expenses",expense,undefined,expenseKey),201).data.id,expenseId)
    checked(await request("POST","/fixed-expenses",{...expense,amountCents:2},undefined,expenseKey),409)
    assert.equal(checked(await request("GET","/fixed-expenses")).monthlyExpensesCents,40000)
    assert.equal(checked(await request("GET",settings)).data,null)
    assert.equal(checked(await request("GET",costs)).data,null)
    checked(await request("PUT",costs,cost),428)
    checked(await request("PUT",costs,{...cost,taxCreditBps:10001},1),422)
    assert.equal(checked(await request("PUT",costs,{...cost,packagingCents:20},1)).revision,2)
    const simulation=checked(await request("POST",settings+"/preview",parameters))
    assert.equal(simulation.calculation.monthlyExpensesCents,40000)
    assert.ok(simulation.suggestedDownPayment.exactBps>0)
    const configuration=checked(await request("PUT",settings,parameters,1))
    assert.equal(configuration.data.monthlyExpensesCents,40000)
    assert.equal(configuration.revision,2)
    checked(await request("PUT",settings,parameters,1),412)
    const old=checked(await request("GET",prices+"/preview"))
    checked(await request("PUT",costs,cost,2))
    checked(await request("POST",prices+"/publish",{digest:old.digest},2,randomUUID()),412)
    assert.equal(checked(await request("GET",prices)).data,null)
    const preview=checked(await request("GET",prices+"/preview")), key=randomUUID()
    // Full rational is 1,256,324.955877... cents before rounding upward.
    assert.equal(preview.items[0].priceWithoutIpiCents,1256325)
    assert.notEqual(preview.digest,old.digest)
    assert.equal(preview.items[0].priceWithIpiCents,1419648)
    const post=()=>request("POST",prices+"/publish",{digest:preview.digest},2,key)
    const [left,right]=await Promise.all([post(),post()])
    const v1=checked(left)
    assert.deepEqual(checked(right),v1)
    assert.equal(checked(await request("POST",prices+"/publish",{digest:preview.digest},2,randomUUID())).id,v1.id)
    assert.equal(v1.version,1)
    const simulate=(id:string)=>request("POST","/commercial/simulate",{...input,versionId:id})
    assert.equal(checked(await request("GET",display)).data.availability.status,"rulesMissing")
    checked(await simulate(v1.id),409)
    checked(await request("PUT",policy,{...rules,directorAutoApproval:true},1),422)
    checked(await request("PUT",policy,rules,1))
    checked(await request("PUT",policy,rules,1),412)
    const ready=checked(await request("GET",display))
    assert.equal(ready.data.availability.status,"ready")
    assert.equal(ready.authority,"managerProfit")
    const first=checked(await simulate(v1.id))
    assert.equal(first.sale.tableTotalCents,preview.items[0].priceWithoutIpiCents)
    const adjusted={...parameters,netMarginBps:1100}
    checked(await request("PUT",settings,adjusted,2))
    assert.equal(checked(await request("GET",display)).data.availability.status,"settingsStale")
    checked(await simulate(v1.id),409)
    const latest=checked(await request("GET",prices+"/preview"))
    const v2=checked(await request("POST",prices+"/publish",{digest:latest.digest},3,randomUUID()))
    assert.equal(v2.version,2)
    checked(await simulate(v1.id),412)
    assert.equal(checked(await post()).id,v1.id)
    assert.equal(checked(await request("GET",prices)).data.id,v2.id)
    await seed.query("DELETE FROM role_permissions WHERE role_id=$1 AND permission_code IN ('sales.approvals.manage','platform.company.manage')",[clerk])
    const seller=checked(await request("GET",display))
    assert.equal(seller.authority,"seller")
    assert.equal(seller.data.availability.status,"ready")
    assert.equal(seller.data.items[0].available,true)
    assert.ok(!JSON.stringify(seller).includes("purchaseCostCents"))
    const current=checked(await simulate(v2.id))
    assert.equal(current.director,null)
    assert.equal(current.version,2)
    assert.equal(current.sale.tableTotalCents,latest.items[0].priceWithoutIpiCents)
    assert.ok(current.sale.totalCents < first.sale.totalCents)
    checked(await request("POST",prices+"/publish",{digest:latest.digest},3,randomUUID()),403)
    await grant(["platform.company.manage"])
    checked(await request("PUT","/fixed-expenses/"+expenseId,{...expense,status:"archived"},1,randomUUID()))
    assert.equal(checked(await request("GET",settings)).monthlyExpensesCents,0)
    checked(await request("PUT","/fixed-expenses/"+expenseId,expense,1,randomUUID()),412)
    const versions=await seed.query("SELECT count(*) FROM price_table_versions WHERE tenant_id=$1",[tenant])
    assert.equal(Number(versions.rows[0].count),2)
    const audit=await seed.query("SELECT details FROM audit_log WHERE tenant_id=$1 AND action='product_costs.updated' ORDER BY details->>'revision'",[tenant])
    assert.deepEqual(audit.rows.at(-1)?.details,{productId:product,previousRevision:2,revision:3})
    const events=await seed.query("SELECT count(*) FROM outbox_events WHERE tenant_id=$1 AND event_type='price_table.published'",[tenant])
    assert.equal(Number(events.rows[0].count),2)
  })
})

import assert from "node:assert/strict"
import test from "node:test"
import { randomUUID } from "node:crypto"
import { stockFixture } from "./stock-fixture.js"

const admin=process.env.API_TS_TEST_ADMIN_URL
test("versioned production reserves components, consumes losses and receives valued finished goods once", {skip:!admin}, async t=>{
  const {app,seed,tenant,close}=await stockFixture(admin!)
  t.after(close)
  const component=randomUUID(),product=randomUUID(),order=randomUUID()
  await seed.query("INSERT INTO role_permissions(role_id,permission_code) SELECT id,unnest(ARRAY['production.read','production.manage']) FROM roles WHERE code='editor'")
  await seed.query(`INSERT INTO products(id,tenant_id,sku,name,unit,price_cents,status) VALUES ($1,$3,'PERFIL','Perfil','M',300,'active'),($2,$3,'BANCO','Banco','UN',5000,'active')`,[component,product,tenant])
  await seed.query("INSERT INTO sales_orders(id,tenant_id,customer_id,customer_name,customer_tax_id,due_date,amount_cents,status) VALUES($1,$2,$2,'Academia','52998224725','2027-01-02',15000,'accepted')",[order,tenant])
  await seed.query("INSERT INTO sales_order_lines(tenant_id,order_id,line_number,product_id,sku,name,unit,quantity_micros,price_cents,amount_cents) VALUES($1,$2,1,$3,'BANCO','Banco','UN',3000000,5000,15000)",[tenant,order,product])
  await seed.query("INSERT INTO sales_order_checkouts(tenant_id,order_id,customer_snapshot,entry_amount_cents,delivery_notes,payment_notes,notes,manufacturing_days,created_at) VALUES($1,$2,'{}',0,'','','',2,'2025-01-08T12:00:00Z')",[tenant,order])
  const headers={authorization:"Bearer fixture-editor-token","x-tenant-id":tenant}
  const post=(url:string,payload:object,rev=1,key=randomUUID().toString())=>app.inject({method:"POST",url:"/api/v1/"+url,headers:{...headers,"if-match":'"'+rev+'"',"idempotency-key":key},payload})
  const get=(url:string)=>app.inject({method:"GET",url:"/api/v1/"+url,headers})
  const receipt=await post("stock/movements",{productId:component,direction:"receipt",quantity:"10.000000",unitCost:"3.000000",reason:"Compra do perfil"})
  assert.equal(receipt.statusCode,201,receipt.body)
  const bom=await post("production/structures/"+product,{components:[{productId:component,quantity:"2.000000"}],previousVersion:0})
  assert.equal(bom.statusCode,201,bom.body)
  const creation=await post("production/orders",{orderId:order})
  assert.equal(creation.statusCode,201,creation.body)
  const job=creation.json().data[0].id
  assert.equal(creation.json().data[0].plannedOn,"2025-01-10")
  assert.equal(creation.json().data[0].overdue,true)
  assert.equal((await get("orders/"+order)).json().overdueProduction[0].id,job)
  const afterReserve=await get("stock?q=PERFIL")
  assert.equal(afterReserve.json().data[0].reserved,"6.000000")
  const kardex=await get("stock/movements?productId="+component)
  assert.equal(kardex.statusCode,200,kardex.body)
  assert.equal(kardex.json().openOrders.data[0].status,"production")
  assert.equal(kardex.json().openOrders.data[0].quantity,"6.000000")
  const over=await post("stock/movements",{productId:component,direction:"issue",quantity:"5.000000",reason:"Saída de terceiro"})
  assert.equal(over.statusCode,409,over.body)
  assert.equal((await post("production/structures/"+product,{components:[{productId:component,quantity:"4.000000"}],previousVersion:1})).statusCode,201)
  const url="production/orders/"+job+"/postings"
  const body={produced:"2.000000",loss:"1.000000",minutes:90,additionalCost:"2.00",reason:"Fabricado e conferido"}
  const key=randomUUID()
  const result=await post(url,body,1,key)
  assert.equal(result.statusCode,200,result.body)
  assert.deepEqual((await post(url,body,1,key)).json(),result.json())
  const detail=(await get("production/orders/"+job)).json()
  assert.equal(detail.data.status,"ready")
  assert.equal(detail.data.bomVersion,1)
  assert.equal(detail.postings[0].value,"20.00")
  assert.equal(detail.postings[0].minutes,90)
  const revised=await post("stock/periods/basis",{kind:"receipt",productId:component,movementId:receipt.json().id,
    freight:"10.00",recoverableTax:"0.00",revision:1,reason:"Rateio posterior do frete desta compra"})
  assert.equal(revised.statusCode,200,revised.body)
  assert.equal((await get("stock?q=BANCO")).json().data[0].stockValue,"26.00")
  const cost=(await get("production/orders/"+job)).json().postings[0]
  assert.deepEqual([cost.recordedValue,cost.value],["20.00","26.00"])
  assert.deepEqual((await seed.query("SELECT quantity_micros FROM stock_balances WHERE product_id=$1",[product])).rows,[{quantity_micros:"2000000"}])
  assert.equal((await get("stock?q=PERFIL")).json().data[0].available,"4.000000")
  assert.equal((await get("orders/"+order)).json().overdueProduction,undefined)
  const stages=(await get("production/stages")).json().data
  const reopen=await post("production/orders/"+job+"/stage",{stageId:stages[0].id},2)
  assert.equal(reopen.statusCode,200,reopen.body)
  assert.equal((await get("stock?q=BANCO")).json().data[0].quantity,"0.000000")
  assert.deepEqual((await get("stock?q=PERFIL")).json().data.map((p:{quantity:string;reserved:string})=>[p.quantity,p.reserved]),[["10.000000","6.000000"]])
  assert.equal((await get("production/orders/"+job)).json().postings[0].reversed,true)

  const again=await post(url,{...body,produced:"3.000000",loss:"0.000000"},3)
  assert.equal(again.statusCode,200,again.body)
  await seed.query("UPDATE stock_balances SET quantity_micros=0 WHERE tenant_id=$1 AND product_id=$2",[tenant,product])
  await seed.query("INSERT INTO stock_movements(id,tenant_id,product_id,direction,quantity_micros,balance_after_micros,reason,source_order_id) VALUES($1,$2,$3,'issue',3000000,0,'Entrega ao cliente',$4)",[randomUUID(),tenant,product,order])
  await seed.query("UPDATE sales_orders SET status='completed',revision=2 WHERE tenant_id=$1 AND id=$2",[tenant,order])
  const receivable=randomUUID()
  await seed.query("INSERT INTO receivables(id,tenant_id,order_id,customer_name,due_date,amount_cents,status) VALUES($1,$2,$3,'Academia','2027-01-02',15000,'open')",[receivable,tenant,order])
  const payment=randomUUID(),bank=randomUUID(),seller=randomUUID()
  await seed.query("INSERT INTO financial_accounts(id,tenant_id,code,name,status,revision,account_type) VALUES($1,$2,'CX-RET','Banco','active',1,'bank')",[bank,tenant])
  await seed.query("INSERT INTO receivable_payments(id,tenant_id,receivable_id,kind,amount_cents,method,reference,occurred_on,financial_account_id) VALUES($1,$2,$3,'receipt',4000,'bank_transfer','Entrada declarada','2027-01-08',$4)",[payment,tenant,receivable,bank])
  await seed.query("INSERT INTO staff(id,tenant_id,code,name,is_employee,is_seller,status) VALUES($1,$2,'OP-01','Vendedor',false,true,'active')",[seller,tenant])
  await seed.query("INSERT INTO commission_accounts(tenant_id,seller_staff_id) VALUES($1,$2)",[tenant,seller])
  await seed.query("INSERT INTO commission_entries(id,tenant_id,seller_staff_id,seller_name,order_id,kind,receipt_id,competence,payment_due,base_cents,commission_rate,ipi_rate,payment_day,amount_cents,reason) VALUES($1,$2,$3,'Vendedor',$4,'receipt',$5,'2027-01-01','2027-02-10',4000,50000,0,10,200,'Recebimento da venda')",[randomUUID(),tenant,seller,order,payment])
  const invoice=randomUUID()
  await seed.query("INSERT INTO fiscal_nfe_drafts(tenant_id,id,environment,model,profile_revision,company_revision,issuer_snapshot,details,products_total_cents) VALUES($1,$2,'production',55,1,1,'{}',$3,15000)",[tenant,invoice,{sourceOrderId:order}])
  await seed.query("INSERT INTO fiscal_nfe_documents(tenant_id,id,source_order_id,environment,status,series,number,issued_at,random_code,signed_xml,access_key,protocol,authorized_xml) VALUES($1,$2,$3,'production','authorized',1,543,'2026-11-16','12345678','<xml/>',repeat('1',44),'protocol','<xml/>')",[tenant,invoice,order])
  const cancelUrl="orders/"+order+"/cancel-completed",cancelKey=randomUUID()
  const cancellation={reason:"Cliente cancelou a venda faturada",occurredOn:"2027-02-01"}
  assert.equal((await post(cancelUrl,cancellation,2,cancelKey)).statusCode,403)
  await seed.query("INSERT INTO role_permissions(role_id,permission_code) SELECT id,'finance.receivables.manage' FROM roles WHERE code='editor'")
  assert.equal((await post(cancelUrl,cancellation,2,cancelKey)).statusCode,403)
  await seed.query("INSERT INTO role_permissions(role_id,permission_code) SELECT id,unnest(ARRAY['finance.commissions.read','finance.commissions.manage']) FROM roles WHERE code='editor'")
  await seed.query("INSERT INTO stock_periods(tenant_id,id,month,closed_by) VALUES($1,$2,'2024-01-01','editor')",[tenant,randomUUID()])
  const refused=await post(cancelUrl,{...cancellation,occurredOn:"2024-01-20"},2,cancelKey)
  assert.equal(refused.statusCode,409,refused.body)
  assert.equal((await get("production/orders/"+job)).json().data.status,"ready")
  const cancelled=await post(cancelUrl,cancellation,2,cancelKey)
  assert.equal(cancelled.statusCode,200,cancelled.body)
  assert.deepEqual((await post(cancelUrl,cancellation,2,cancelKey)).json(),cancelled.json())
  const summary=cancelled.json().data
  assert.equal(summary.receivableId,receivable)
  assert.equal(summary.fiscalCancellation.status,"pending")
  assert.equal(summary.paymentReversalIds.length,1)
  assert.equal(summary.reconciliation.commission.reversedEntries,1)
  assert.equal((await seed.query("SELECT amount_cents,payment_due::text FROM commission_entries WHERE reversal_id=$1",[summary.paymentReversalIds[0]])).rows[0].payment_due,"2027-03-10")
  assert.equal((await seed.query("SELECT amount_cents FROM financial_account_entries WHERE account_id=$1 AND direction='debit'",[bank])).rows[0].amount_cents,"4000")
  assert.deepEqual((await get("orders/"+order+"/cancellations")).json().data,[summary])
  assert.deepEqual(summary.reconciliation.production.orderIds,[job])
  const compensations=[...summary.stockMovementIds,...summary.reconciliation.production.stockMovementIds]
  assert.equal(new Set(compensations).size,3)
  const returned=await seed.query("SELECT COUNT(*)::int AS total FROM stock_movements WHERE tenant_id=$1 AND id=ANY($2::uuid[]) AND effective_on=$3::date AND reverses_id IS NOT NULL",[tenant,compensations,cancellation.occurredOn])
  assert.equal(returned.rows[0].total,3)
  assert.equal((await get("stock?q=BANCO")).json().data[0].quantity,"0.000000")
  assert.equal((await get("stock?q=PERFIL")).json().data[0].available,"10.000000")
  assert.equal((await get("production/orders/"+job)).json().data.status,"cancelled")
  assert.equal((await seed.query("SELECT status FROM receivables WHERE id=$1",[receivable])).rows[0].status,"cancelled")
})

test("teclado, obrigatório, opcional e disabled preservam formulário e histórico", async ({ page }) => {
  await page.goto(`/vendas/pedidos/${record}/editar`)
  await page.getByText("Acabamentos", { exact: false }).first().click()
  const trigger = page.getByRole("combobox", { name: "Cor da estrutura de Equipamento com cores", exact: true })
  await expect(trigger).toContainText("Vermelho histórico")
  await trigger.click()
  await page.getByRole("option", { name: "Escolha uma cor", exact: true }).click()
  const required = trigger.locator("xpath=..").locator("input[required]")
  expect(await required.evaluate((input: HTMLInputElement) => input.checkValidity())).toBe(false)
  await trigger.focus(); await trigger.press("ArrowDown"); await page.keyboard.press("Home"); await page.keyboard.press("ArrowDown"); await page.keyboard.press("ArrowDown"); await page.keyboard.press("Enter")
  await expect(trigger).toContainText("Piano Black")
  expect(await required.evaluate((input: HTMLInputElement) => input.checkValidity())).toBe(true)
  const arms = page.getByRole("combobox", { name: "Cor dos braços de Equipamento com cores", exact: true })
  await arms.click(); await page.getByRole("option", { name: "Manter sem seleção", exact: true }).click()
  await expect(arms).toContainText("Manter sem seleção")
  await trigger.click()
  await trigger.evaluate(element => { element.closest("fieldset")!.disabled = true })
  await expect(trigger).toBeDisabled()
  await expect(page.getByRole("listbox", { name: "Cor da estrutura de Equipamento com cores", exact: true })).toBeHidden()
  await trigger.evaluate(element => { element.closest("fieldset")!.disabled = false })
  await expect(trigger).toBeEnabled()
})

test("paleta combinada usa Khaki S-Force e mantém as duas referências originais", async ({ page }) => {
  await page.route(`**/api/erp/products/${productId}`, route => route.fulfill({ json: { tenantId: tenant, data: { id: productId, finishingPalette: "dhz-combined", structureColors: ["Piano Black"], swingArmColors: ["Ocean Blue"], upholsteryColors: ["Black", "Khaki"], upholsteryConfigurable: true, hasPhoto: false } } }))
  await page.goto(`/vendas/pedidos/${record}/editar`)
  await page.getByText("Acabamentos", { exact: false }).first().click()
  await expect(page.getByRole("link", { name: /Ver paleta original e combinações/ })).toHaveCount(2)
  const trigger = page.getByRole("combobox", { name: "Cor do estofado de Equipamento com cores", exact: true })
  await trigger.click()
  const khaki = page.getByRole("option", { name: "Khaki", exact: true })
  await expect(khaki.locator("[data-catalog-color-photo]")).toHaveCSS("background-image", /dhz-s-force-original-colors/)
  await khaki.click()
  await expect(trigger).toContainText("Khaki")
})


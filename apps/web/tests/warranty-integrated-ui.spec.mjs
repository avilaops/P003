import { expect, test } from "@playwright/test"
import { installFrontendSession } from "./helpers/frontend-fixture.ts"
import { localCommercePostgres } from "../../api-ts/test/local-commerce-postgres.ts"

test("garantia aberta e encaminhada pela interface persiste no PostgreSQL pelo BFF e Fastify", async ({ page, context, baseURL }) => {
  test.skip(!process.env.API_TS_TEST_ADMIN_URL, "Requer o banco PostgreSQL local descartável")
  await localCommercePostgres(async ({ app, seed, tenant, clerk }) => {
    await seed.query("INSERT INTO role_permissions(role_id,permission_code) VALUES($1,'service.warranties.read'),($1,'service.warranties.manage')",[clerk])
    await app.listen({ host: "127.0.0.1", port: 33119 })
    await installFrontendSession(context, baseURL, tenant, "cashier")
    await page.goto("/vendas/garantias/novo")
    await page.getByLabel("Título",{ exact: true }).fill("Folga no equipamento")
    await page.getByLabel("Descrição",{ exact: true }).fill("Equipamento com folga durante o ajuste da base.")
    await page.getByRole("button",{ name: "Abrir garantia" }).click()
    await expect(page).toHaveURL(/\/vendas\/garantias\/[0-9a-f-]{36}$/)
    const id = new URL(page.url()).pathname.split("/").pop()
    await page.getByLabel("Fila",{ exact: true }).fill("Bancada local")
    const result = page.waitForResponse(response => response.url().endsWith("/assignment") && response.request().method() === "POST")
    await page.getByRole("button",{ name: "Salvar triagem" }).click()
    expect((await result).status()).toBe(200)
    await page.reload()
    await expect(page.getByLabel("Fila",{ exact: true })).toHaveValue("Bancada local")
    const saved = await seed.query("SELECT title,queue,revision::int FROM warranty_cases WHERE tenant_id=$1 AND id=$2",[tenant,id])
    expect(saved.rows).toEqual([{title:"Folga no equipamento",queue:"Bancada local",revision:2}])
    const audit = await seed.query("SELECT action FROM audit_log WHERE tenant_id=$1 AND entity_id=$2 ORDER BY action",[tenant,id])
    expect(audit.rows.map(row => row.action)).toEqual(["warranty.case.assigned","warranty.case.opened"])
    const pdf=Buffer.from("%PDF-1.4\nEvidencia da garantia local\n%%EOF")
    await page.getByLabel("Título do registro").fill("Laudo recebido na triagem")
    await page.getByLabel("Foto, vídeo ou PDF").setInputFiles({name:"laudo.pdf",mimeType:"application/pdf",buffer:pdf})
    await page.getByRole("button",{name:"Salvar registro"}).click()
    const attachment=page.getByRole("link",{name:"laudo.pdf"})
    await expect(attachment).toBeVisible()
    const file=await context.request.get(new URL(await attachment.getAttribute("href"),baseURL).href)
    expect(file.status()).toBe(200)
    expect(await file.body()).toEqual(pdf)
    await page.goto("/vendas/garantias/indicadores")
    await expect(page.getByRole("link",{name:"Folga no equipamento"})).toBeVisible()
    await page.getByLabel("Abertura até").fill("2000-01-01")
    await page.getByRole("button",{name:"Aplicar período"}).click()
    await expect(page.getByText("Nenhum protocolo encontrado.")).toBeVisible()
    await page.getByLabel("Abertura até").fill("")
    await page.getByRole("button",{name:"Aplicar período"}).click()
    await expect(page.getByRole("link",{name:"Folga no equipamento"})).toBeVisible()
  })
})
